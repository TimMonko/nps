@app.cell(hide_code=True)
def reload_data(CSV, pd, rebuild, subprocess, sys):
    if rebuild.value:
        subprocess.run([sys.executable, str(_build)], check=True, cwd=_repo)

    df0 = pd.read_csv(CSV, dtype=str)
    for col in ("release_date", "dev_window_first", "dev_window_last"):
        df0[col] = pd.to_datetime(df0[col], errors="coerce")
    for col in ("new_contributors", "new_per_month", "dev_months", "months_between_releases"):
        df0[col] = pd.to_numeric(df0[col], errors="coerce")
    df0 = df0.dropna(subset=["new_contributors", "dev_window_first", "dev_window_last"])

    return (df0,)



@app.cell
def _(
    df0,
    go,
    highlight,
    label_min,
    label_rotation,
    min_dev_days,
    min_release,
    show_0_1_0,
    show_labels,
):
    df = df0.copy()
    df["dev_days"] = (df["dev_window_last"] - df["dev_window_first"]).dt.days
    if min_dev_days.value > 0:
        df = df[df["dev_days"] >= min_dev_days.value]
    if min_release.value.strip():
        key = tuple(int(x) for x in min_release.value.strip().split("."))
        df = df[df["release"].map(
            lambda v: tuple(int(x) for x in v.split(".")) >= key)]
    df = df.sort_values("dev_window_first").reset_index(drop=True)
    if not show_0_1_0.value:
        df = df[df["release"] != "0.1.0"].reset_index(drop=True)

    x_mid = df["dev_window_first"] + (df["dev_window_last"] - df["dev_window_first"]) / 2
    dev_ms = (df["dev_window_last"] - df["dev_window_first"]).dt.total_seconds() * 1000
    label_meta = []
    for _, r in df.iterrows():
        c = int(r["new_contributors"])
        if c == 0:
            label_meta.append((f"{r['release']}::{c}", True))      # dim
        elif c >= label_min.value:
            label_meta.append((f"{r['release']}::{c}", False))     # normal
        else:
            label_meta.append(("", False))
    labels = [t for t, _ in label_meta]
    dimmed = [is_dim for _, is_dim in label_meta]
    colors = ["#2e8b57" if c >= highlight.value else "#4477aa" for c in df["new_contributors"]]

    fig = go.Figure()
    fig.add_trace(go.Bar(
        x=x_mid, y=df["new_per_month"], width=dev_ms, marker_color=colors,
        customdata=df[["release", "new_contributors",
                       "dev_window_first", "dev_window_last"]],
        hovertemplate=(
            "<b>%{customdata[0]}</b><br>"
            "new contributors: %{customdata[1]}<br>"
            "rate: %{y:.1f} / month<br>"
            "dev window: %{customdata[2]} → %{customdata[3]}<extra></extra>"
        ),
    ))
    if show_labels.value:
        # labels as annotations so they render at a uniform size:
        # Plotly auto-scales Bar text to fit each bar's width
        for xi, yi, lab, is_dim in zip(x_mid, df["new_per_month"], labels, dimmed):
            if lab:
                fig.add_annotation(
                    x=xi, y=yi, text=lab,
                    textangle=label_rotation.value, showarrow=False,
                    font=dict(size=8, color="#b8b8b8" if is_dim else "#262626"),
                    xanchor="center", yanchor="bottom", yshift=2,
                )
    fig.update_layout(
        title="napari new contributors per release (bar area = new contributors)",
        xaxis_title="Timeline (release dates)",
        yaxis_title="New contributors / month",
        hovermode="closest",
        height=520,
        margin=dict(t=70, b=40),
    )
    total_new = int(df["new_contributors"].sum())
    n_releases = len(df)

    return df, fig, n_releases, total_new


